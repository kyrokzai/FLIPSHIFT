/** Для должностей без готового набора резюме собираются из условий самой вакансии. */
function generated(draft: VacancyDraft): DemoResume[] {
  const title = draft.title ?? "Специалист";
  const city = draft.city ?? "Астана";
  const duties = draft.responsibilities.length ? draft.responsibilities : [`Работа по профилю «${title}»`];
  const half = duties.slice(0, Math.max(1, Math.ceil(duties.length / 2)));
  const list = (items: string[]) => items.map((item) => `— ${item}`).join("\n");

  return [
    {
      name: "Демо-кандидат А.",
      resumeText: `Демо-кандидат А.\nЖелаемая должность: ${title}\nГород: ${city}\n\nОпыт работы: 5 лет\n2021 — настоящее время. Компания «Демо Один»\n${title}\n${list(duties)}\n${list(draft.requirements)}`,
    },
    {
      name: "Демо-кандидат Б.",
      resumeText: `Демо-кандидат Б.\nЖелаемая должность: ${title}\nГород: ${city}\n\nОпыт работы: 2 года\n2024 — настоящее время. Компания «Демо Два»\n${title}\n${list(half)}`,
    },
    {
      name: "Демо-кандидат В.",
      resumeText: `Демо-кандидат В.\nГород: Алматы\n\nОпыт работы: 1 год\n2025 — настоящее время. Компания «Демо Три»\nПомощник администратора\n— Работа с документами и входящими звонками\nХочу сменить профессию.`,
    },
  ];
}

export function demoResumesFor(draft: VacancyDraft): DemoResume[] {
  const title = normalize(draft.title ?? "");
  if (/барист/.test(title)) return BARISTA;
  if (isSalesRole(draft.title)) return SALES;
  return generated(draft);
}
