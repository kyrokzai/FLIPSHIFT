const BANKS: Partial<Record<TemplateId, Bank>> = { sales: SALES, barista: BARISTA };

/** Уровень вымышленного кандидата — по соответствию его резюме вакансии. */
export function demoTier(candidate: Candidate): DemoTier {
  const score = candidate.analysis?.score ?? 0;
  return score >= 75 ? "strong" : score >= 50 ? "medium" : "weak";
}

/** Вымышленный ответ на шаг. Средний уровень чередует сильные и слабые ответы. */
export function demoAnswer(templateId: TemplateId, situationId: string, step: number, tier: DemoTier): string {
  const entry = BANKS[templateId]?.[situationId] ?? GENERIC;
  const strong = tier === "strong" || (tier === "medium" && step % 2 === 1);
  return strong ? entry.strong : entry.weak;
}
