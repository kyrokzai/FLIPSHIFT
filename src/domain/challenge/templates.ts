/** Шаблон по названию должности. Для остальных профессий — свой сценарий. */
export function suggestTemplate(title: string | null): TemplateId {
  const value = (title ?? "").toLowerCase().replace(/ё/g, "е");
  if (/продаж|продав|sales|торгов|клиент|сбыт|менеджер по развитию/.test(value)) return "sales";
  if (/барист|бармен|официант|кофе/.test(value)) return "barista";
  if (/поддержк|оператор|колл|call|support/.test(value)) return "support";
  if (/бухгалтер|экономист|финанс/.test(value)) return "accountant";
  if (/логист|курьер|водител|склад|диспетчер/.test(value)) return "logistics";
  return "custom";
}
