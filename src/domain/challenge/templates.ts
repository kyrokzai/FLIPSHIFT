import type { Difficulty, TemplateId } from "./schema";

/**
 * Шаблоны практических проверок. Шаблон — это данные: ситуации и критерии.
 * Новая профессия добавляется новым шаблоном, без изменения движка.
 *
 * Признаки в критериях — наблюдаемые элементы ответа (вопрос, аргумент,
 * предложенный шаг). Они не оценивают личность, стиль речи или грамотность.
 */

export interface Marker {
  /** Как признак называется в отчёте: «собственное производство». */
  label: string;
  pattern: RegExp;
}

interface CriterionBase {
  id: string;
  label: string;
  /** Что именно проверяет критерий — для работодателя. */
  description: string;
  defaultWeight: number;
  /** Что уточнить на собеседовании, если навык не проявился. */
  verifyIfMissing: string;
  /** Что проверить вживую, даже если навык проявился в тексте. */
  verifyIfShown: string;
}

/** Вопросы собеседнику. topic — о чём вопрос; без topic считается любой вопрос. */
export interface QuestionsCriterion extends CriterionBase {
  kind: "questions";
  topic: RegExp | null;
  /** Сколько вопросов нужно, чтобы навык считался проявленным. */
  target: number;
}

/** Разные содержательные признаки в ответах: аргументы, этапы, инструменты. */
export interface MarkersCriterion extends CriterionBase {
  kind: "markers";
  markers: Marker[];
  target: number;
}

/** Ответ на возражение: признание сути возражения и предложенный выход в одном ответе. */
export interface ObjectionCriterion extends CriterionBase {
  kind: "objection";
  acknowledge: Marker[];
  resolve: Marker[];
}

/** Конкретный следующий шаг — особенно в последнем ответе. */
export interface NextStepCriterion extends CriterionBase {
  kind: "next_step";
  markers: Marker[];
}

export type TemplateCriterion = QuestionsCriterion | MarkersCriterion | ObjectionCriterion | NextStepCriterion;

export interface Situation {
  id: string;
  title: string;
  prompts: Record<Difficulty, string>;
  /** Ситуация содержит возражение — по ответу на неё оценивается работа с возражениями. */
  objection: boolean;
}

export interface ChallengeTemplate {
  id: TemplateId;
  title: string;
  /** Кнопка в карточке кандидата. */
  action: string;
  /** Кого изображает собеседник. */
  counterpart: string;
  intro: string;
  situations: Situation[];
  criteria: TemplateCriterion[];
}

